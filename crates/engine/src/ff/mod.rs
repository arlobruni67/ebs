/// Pointer to a field at a generated byte offset.
#[inline]
pub unsafe fn field<T>(base: *mut c_void, offset: usize) -> *mut T {
    (base as *mut u8).add(offset) as *mut T
}
#[inline]
pub unsafe fn get<T: Copy>(base: *mut c_void, offset: usize) -> T {
    *field::<T>(base, offset)
}
#[inline]
pub unsafe fn set<T>(base: *mut c_void, offset: usize, v: T) {
    *field::<T>(base, offset) = v
}

pub fn err_str(code: i32) -> String {
    let mut buf = [0 as c_char; 256];
    unsafe { av_strerror(code, buf.as_mut_ptr(), buf.len()) };
    unsafe { CStr::from_ptr(buf.as_ptr()) }.to_string_lossy().into_owned()
}

#[derive(Debug)]
pub struct FfError {
    pub what: String,
    pub code: i32,
}
impl std::fmt::Display for FfError {
    fn fmt(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
        write!(f, "{}: {}", self.what, err_str(self.code))
    }
}
impl std::error::Error for FfError {}

pub fn check(ret: i32, what: impl Into<String>) -> Result<i32, FfError> {
    if ret < 0 {
        Err(FfError { what: what.into(), code: ret })
    } else {
        Ok(ret)
    }
}

pub fn cstr(s: &str) -> CString {
    CString::new(s.replace('\0', "")).unwrap()
}

/// Verifies the DLLs are the FFmpeg major versions the offsets were generated for.
pub fn init() -> anyhow::Result<()> {
    static ONCE: std::sync::OnceLock<Result<(), String>> = std::sync::OnceLock::new();
    ONCE.get_or_init(|| {
        let c = unsafe { avcodec_version() } >> 16;
        let u = unsafe { avutil_version() } >> 16;
        if c != AVCODEC_MAJOR || u != AVUTIL_MAJOR {
            return Err(format!("FFmpeg version mismatch: avcodec {c} (want {AVCODEC_MAJOR}), avutil {u} (want {AVUTIL_MAJOR})"));
        }
        let lvl = match std::env::var("ARLO_FFLOG").as_deref() {
            Ok("verbose") => AV_LOG_VERBOSE,
            Ok("off") => AV_LOG_QUIET,
            _ => AV_LOG_WARNING,
        };
        unsafe { av_log_set_level(lvl) };
        Ok(())
    })
    .clone()
    .map_err(anyhow::Error::msg)
}

/// Owned AVDictionary of encoder/muxer options.
pub struct Dict(pub *mut AVDictionary);
impl Dict {
    pub fn new() -> Self {
        Dict(std::ptr::null_mut())
    }
    pub fn set(&mut self, k: &str, v: &str) {
        let (k, v) = (cstr(k), cstr(v));
        unsafe { av_dict_set(&mut self.0, k.as_ptr(), v.as_ptr(), 0) };
    }
    pub fn keys(&self) -> Vec<String> {
        let mut out = Vec::new();
        let mut e: *mut AVDictionaryEntry = std::ptr::null_mut();
        let empty = cstr("");
        loop {
            e = unsafe { av_dict_get(self.0, empty.as_ptr(), e, AV_DICT_IGNORE_SUFFIX) };
            if e.is_null() {
                break;
            }
            out.push(unsafe { CStr::from_ptr((*e).key) }.to_string_lossy().into_owned());
        }
        out
    }
}
impl Default for Dict {
    fn default() -> Self {
        Self::new()
    }
}
impl Drop for Dict {
    fn drop(&mut self) {
        unsafe { av_dict_free(&mut self.0) }
    }
}

/// An owned AVPacket that may be sent to another thread.
pub struct Packet(pub *mut AVPacket);
unsafe impl Send for Packet {}
impl Packet {
    pub fn size(&self) -> i32 {
        unsafe { get(self.0, AVPacket_size) }
    }
}
impl Drop for Packet {
    fn drop(&mut self) {
        unsafe { av_packet_free(&mut self.0) }
    }
}

/// An owned AVFrame that may be sent to another thread.
pub struct Frame(pub *mut AVFrame);
unsafe impl Send for Frame {}
impl Drop for Frame {
    fn drop(&mut self) {
        if !self.0.is_null() {
            unsafe { av_frame_free(&mut self.0) }
        }
    }
}

/// avio_tell is a header-only inline in FFmpeg.
pub unsafe fn avio_tell(pb: *mut AVIOContext) -> i64 {
    avio_seek(pb, 0, 1)
}
